"""Stage 2 Step 18 — figures built ONLY from CONFIRMED published values.

No CheXpert file has been downloaded. Every number in this script is transcribed
from a primary source and carries its citation in `SOURCE` below; nothing is
assumed, estimated or fabricated. Values derived by arithmetic from those numbers
are labelled INFERRED on the figure itself.

Figures that need the actual CSV or image files are NOT produced here — they are
listed as DEFERRED in docs/dataset_analysis.md §18.1 and are generated by
analyze_metadata.py / validate_images.py once the data arrives.

Run:  python src/data/plot_published_stats.py
"""

